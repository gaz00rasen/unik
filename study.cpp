#include <iostream>

void matrix(int(&mat)[4][3]) // void функция для вывода матрицы размера 4x3
{
	for (int i = 0; i < 4; i++) // цикл перебора строк
	{
        printf("[\t"); // в каждой строке печатаем "[" и отступаем табуляцией
		for (int j = 0; j < 3; j++) { std::cout << mat[i][j] << "\t"; } // цикл перебора столбцов
        printf("]\n"); // закрываем строку
	}
}

int main()
{
	std::setlocale(LC_ALL, "Russian"); // подключаем русский язык для консоли
    int mat[4][3] = { {1, -1, 1}, {-1, 8, -1}, {1, 8, 1}, {-1, 1, -1} }; // задаем значения исходной матрицы 4x3

    char choice;
    printf("Использовать готовую матрицу? Y/N\n");
    std::cin >> choice; // запрашиваем у пользователя, какую матрицу использовать: готовую или свою
    if (choice == 'N' || choice == 'n')
    {
        printf("Введите 12 чисел для матрицы:\n");
		for (int i = 0; i < 4; i++) // цикл перебора четырех (i<4, от 0 до 3) строк
        {
			for (int j = 0; j < 3; j++) { std::cin >> mat[i][j]; } // цикл перебора трех столбцов (j<3, от 0 до 2), ввод значений в матрицу
        }
	} // сначала перебираем строки, затем столбцы, чтобы заполнить матрицу значениями

    printf("Исходная матрица:\n");
	matrix(mat); // выводим исходную матрицу на экран, или ту, которую ввел пользователь

	int max_abs = abs(mat[0][0]), max_num = mat[0][0], max_cnt = 0; // задаем переменные для хранения самого частого значения по модулю, самого числа и кол-ва его вхождений
	int min_num = mat[0][0], min_abs = 13, min_cnt = 13; /* задаем переменные для самого редкого числа, минимального кол-ва вхождений по модулю и точного кол-ва вхождений
                                                            (13 - так как в матрице 12 элементов, т.е. любое число встретится меньше 13 раз, и на первом же шаге цикл запишет минимум) */

    for (int i = 0; i < 4; i++) // перебор строк
    {
        for (int j = 0; j < 3; j++) // перебор столбцов
        {
            int sch_ABS = 0, sch_CNT = 0; // задаем (или обнуляем) счетчики для подсчета, сколько раз встретится модуль числа, и сколько раз встретится само число с тем же знаком
            for (int a = 0; a < 4; a++) // цикл, заново сравнивающий значения элементов в строке
            {
                for (int b = 0; b < 3; b++) // цикл, заново сравнивающий значения элементов в столбце
                {
                    if (abs(mat[a][b]) == abs(mat[i][j])) { sch_ABS++; } // если значение совпало по модулю, к счетчику по модулю добавляем 1
					if (mat[a][b] == mat[i][j]) { sch_CNT++; } // если значение совпало с тем же знаком, к счетчику по тому же знаку добавляем 1
                }
            }
			if (sch_ABS > max_cnt) // если модуль текущего числа встретился больше раз, чем предыдущий максимум, то записываем его как новый максимум
            {
                max_cnt = sch_ABS; 
                max_abs = abs(mat[i][j]);
                max_num = mat[i][j];
            }

			if (sch_ABS < min_abs || (sch_ABS == min_abs && sch_CNT < min_cnt)) /* обновляем самое редкое число, если его модуль встретился меньше раз, чем предыдущий минимум, или 
                                                                                   если модуль встретился столько же раз, но само число с тем же знаком встретилось меньше раз */
            {
                min_abs = sch_ABS; 
                min_cnt = sch_CNT;
                min_num = mat[i][j];
            }
        }
    }

    if (max_abs != abs(min_num)) // защита, если вся матрица состоит из одного и того же модуля (5 и -5), тогда самое редкое и самое частое совпадает, менять ничего не нужно
    {
        for (int i = 0; i < 4; ++i)
        {
            for (int j = 0; j < 3; ++j)
            {
                if (abs(mat[i][j]) == max_abs) { mat[i][j] = min_num; continue; } // если нашли элемент с самым частым модулем, заменяем его на самое редкое число и сразу переходим к следующей ячейке
                if (abs(mat[i][j]) == abs(min_num)) { mat[i][j] = max_num; } // если в ячейке и так лежит самое редкое число по модулю, меняем его на самое частое
            }
        }
    }

    printf("Промежуточный результат (замена |%d| и %d):\n", max_abs, min_num);
    matrix(mat); // выводим промежуточный результат замены

    for (int i = 0; i < 4; ++i)
    {
        if (mat[i][0] == mat[i][1] && mat[i][1] == mat[i][2]) { mat[i][0] = mat[i][1] = mat[i][2] = 0; } // если в строке все три числа одинаковые, заменяем их на нули
    }

    printf("Итоговая матрица:\n");
    matrix(mat); // выводим итоговую матрицу
}
